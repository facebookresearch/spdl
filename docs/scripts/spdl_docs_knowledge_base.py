def _default_sources() -> list[dict[str, Any]]:
    return [
        {
            "source": f"../../tools/skills/{source}",
            "target": f"{_ROOT}/{target}".rstrip("/"),
            "parent": "knowledge_base/index",
            "caption": caption,
            "exclude": exclude,
            "optional": source == "optimization/techniques/*.md",
        }
        for source, target, caption, exclude in _DEFAULT_SOURCES
    ]


def _destination(srcdir: Path, relative: str) -> Path:
    root = srcdir / _ROOT
    path = srcdir / relative
    if Path(relative).is_absolute() or ".." in Path(relative).parts:
        raise ConfigError(f"Invalid generated knowledge-base path: {relative}")
    if not root.resolve().is_relative_to(
        srcdir.resolve()
    ) or not path.resolve().is_relative_to(root.resolve()):
        raise ConfigError(f"Knowledge-base output must stay under {_ROOT}: {relative}")
    return path


def _remove_pending(path: Path) -> None:
    # This reserved temporary namespace is never read as a Sphinx document.
    for pending in path.parent.glob(f".{path.name}.spdl-kb-*.tmp"):
        if pending.is_symlink() or not pending.is_file():
            raise ConfigError(f"Invalid knowledge-base temporary file: {pending}")
        pending.unlink()


def _write_atomic(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    _remove_pending(path)
    pending: Path | None = None
    try:
        with NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            dir=path.parent,
            prefix=f".{path.name}.spdl-kb-",
            suffix=".tmp",
            delete=False,
        ) as stream:
            pending = Path(stream.name)
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        pending.replace(path)
    finally:
        original = sys.exception()
        if pending is not None:
            try:
                pending.unlink(missing_ok=True)
            except OSError as error:
                if original is None:
                    raise
                original.add_note(f"Temporary-file cleanup also failed: {error}")


def _validate_generated_source(path: Path) -> None:
    if not path.exists() and not path.is_symlink():
        return
    if path.is_symlink() or not path.is_file():
        raise ConfigError(f"Invalid generated knowledge-base file: {path}")
    marker = _MARKER.encode("utf-8")
    with path.open("rb") as stream:
        if stream.read(len(marker)) != marker:
            raise ConfigError(f"Refusing to remove unowned knowledge-base file: {path}")


def _remove_generated(srcdir: Path) -> None:
    manifest = _destination(srcdir, _ROOT + "/manifest.json")
    _remove_pending(manifest)
    if not manifest.exists():
        return
    names = json.loads(manifest.read_text(encoding="utf-8"))
    if not isinstance(names, list) or any(not isinstance(name, str) for name in names):
        raise ConfigError("Invalid knowledge-base generated-file manifest")
    paths = [_destination(srcdir, name) for name in names]
    for path in paths:
        _validate_generated_source(path)
    for path in paths:
        _remove_pending(path)
        path.unlink(missing_ok=True)
    manifest.unlink()


def _collect(app: Sphinx) -> tuple[dict[str, Path], dict[str, list[dict[str, Any]]]]:
    srcdir = Path(app.srcdir)
    pages: dict[str, Path] = {}
    trees: dict[str, list[dict[str, Any]]] = {}
    groups = [
        *app.config.spdl_knowledge_base_sources,
        *app.config.spdl_knowledge_base_extra_sources,
    ]
    for group in groups:
        pattern = srcdir / group["source"]
        if "**" in str(pattern) or any(char in str(pattern.parent) for char in "*?["):
            raise ConfigError(
                "Knowledge-base sources must use nonrecursive filename patterns"
            )
        sources = sorted(pattern.parent.glob(pattern.name))
        if not sources:
            if group.get("optional", False):
                continue
            raise ConfigError(f"No Markdown sources match {pattern}")
        docnames = []
        for source in sources:
            if source.name in group.get("exclude", []):
                continue
            if not source.is_file() or source.suffix != ".md":
                raise ConfigError(f"Not a Markdown source: {source}")
            docname = f"{group['target']}/{source.stem}"
            _destination(srcdir, docname + ".md")
            if docname in pages:
                raise ConfigError(f"Duplicate generated knowledge-base page: {docname}")
            pages[docname] = source
            docnames.append(docname)
        trees.setdefault(group["parent"], []).append(
            {
                "caption": group["caption"],
                "docnames": docnames,
                "target": group["target"],
                "summary": group.get(
                    "summary",
                    _CATEGORY_SUMMARIES.get(group["caption"], "Choose a topic below."),
                ),
            }
        )
    return pages, trees


def _category_pages(
    pages: dict[str, Path], trees: dict[str, list[dict[str, Any]]]
) -> dict[str, str]:
    hubs: dict[str, str] = {}
    for groups in trees.values():
        for group in groups:
            slug = re.sub(r"[^a-z0-9]+", "-", group["caption"].lower()).strip("-")
            hub = f"{group['target']}/_categories/{slug}"
            if not slug or hub in hubs:
                raise ConfigError(
                    f"Duplicate or invalid knowledge-base category: {group['caption']}"
                )
            group["hub"] = hub
            lines = [
                f"# {group['caption']}",
                "",
                group["summary"],
                "",
            ]
            for name in group["docnames"]:
                original = pages[name]
                title = next(
                    (
                        line[2:]
                        for line in original.read_text(encoding="utf-8").splitlines()
                        if line.startswith("# ")
                    ),
                    original.stem,
                )
                relative = posixpath.relpath(name + ".md", posixpath.dirname(hub))
                lines.append(f"- [{title}]({relative})")
            hubs[hub] = "\n".join(lines) + "\n"
    return hubs


class _LockOwner(Protocol):
    _spdl_knowledge_base_lock: FileLock


class _LabelConfig(Protocol):
    autosectionlabel_prefix_document: bool


def _acquire(app: Sphinx) -> None:
    path = Path(app.srcdir) / "knowledge_base/.sphinx.lock"
    if path.is_symlink() or not path.resolve().is_relative_to(
        Path(app.srcdir).resolve()
    ):
        raise ConfigError("Knowledge-base lock must stay inside the source directory")
    path.parent.mkdir(parents=True, exist_ok=True)
    lock = FileLock(str(path))
    try:
        lock.acquire(timeout=0)
    except Timeout as error:
        raise ConfigError(
            "Another knowledge-base build is using this source directory"
        ) from error
    cast(_LockOwner, app)._spdl_knowledge_base_lock = lock


def _prepare(app: Sphinx) -> None:
    _acquire(app)
    complete = False
    try:
        _generate(app)
        complete = True
    finally:
        if not complete:
            _cleanup(app, sys.exception())


def _generate(app: Sphinx) -> None:
    srcdir = Path(app.srcdir)
    previous_state = app.env.domaindata.get(_KEY, {})
    previous = previous_state.get("trees", {})
    _remove_generated(srcdir)
    pages, trees = _collect(app)
    hubs = _category_pages(pages, trees)
    outputs = set(pages) | set(hubs)
    destinations = [_destination(srcdir, name + ".md") for name in sorted(outputs)]
    for destination in destinations:
        _validate_generated_source(destination)
    for destination in destinations:
        destination.unlink(missing_ok=True)
    manifest = _destination(srcdir, _ROOT + "/manifest.json")
    _write_atomic(
        manifest, json.dumps([str(path.relative_to(srcdir)) for path in destinations])
    )
    for docname in sorted(outputs):
        destination = _destination(srcdir, docname + ".md")
        destination.parent.mkdir(parents=True, exist_ok=True)
        content = (
            hubs[docname]
            if docname in hubs
            else pages[docname].read_text(encoding="utf-8")
        )
        _write_atomic(destination, _MARKER + "\n" + content)
    app.env.domaindata[_KEY] = {
        "pages": pages,
        "trees": trees,
        "hubs": {group["hub"]: group for groups in trees.values() for group in groups},
        "outputs": outputs,
        "reread": set(previous) | set(trees),
        "previous_pages": set(
            previous_state.get("outputs", previous_state.get("pages", {}))
        ),
    }
    _record_outputs(app)
    logger.debug("Prepared %d knowledge-base pages", len(pages))


def _read_docs(app: Sphinx, env: BuildEnvironment, docnames: list[str]) -> None:
    state = env.domaindata[_KEY]
    missing = set(state["trees"]) - env.found_docs
    if missing:
        raise ConfigError(
            f"Knowledge-base parent documents are missing or excluded: {sorted(missing)}"
        )
    parents = state["reread"] & env.found_docs
    docnames.extend(sorted(parents - set(docnames)))


def _dependencies(app: Sphinx, docname: str, source: list[str]) -> None:
    original = app.env.domaindata[_KEY]["pages"].get(docname)
    if original is not None:
        app.env.note_dependency(str(original))
        app.env.note_dependency(str(original.resolve()))


def _navigation(app: Sphinx, doctree: Any) -> None:
    state = app.env.domaindata[_KEY]
    docname = app.env.docname
    groups = state["trees"].get(docname, [])
    entries = [(group["caption"], group["hub"]) for group in groups]
    if app.builder.name == "singlehtml" and docname in state["hubs"]:
        entries = [(None, name) for name in state["hubs"][docname]["docnames"]]
    elif docname in state["pages"]:
        app.env.metadata.setdefault(docname, {})["orphan"] = True
    if not entries:
        return
    tree = addnodes.toctree()
    tree["parent"] = docname
    tree["entries"] = entries
    tree["includefiles"] = [name for _, name in entries]
    tree["caption"] = None
    tree["rawcaption"] = ""
    tree["maxdepth"] = 1
    tree["glob"] = False
    tree["hidden"] = False
    tree["includehidden"] = False
    tree["titlesonly"] = True
    tree["numbered"] = 0
    section = next(
        (child for child in doctree.children if isinstance(child, nodes.section)), None
    )
    if section is None:
        raise ConfigError(
            f"Knowledge-base navigation parent has no document section: {docname}"
        )
    section.append(tree)


def _label_scope(app: Sphinx, doctree: Any) -> None:
    state = app.env.domaindata[_KEY]
    if (
        app.env.docname in state["outputs"]
        and "sphinx.ext.autosectionlabel" in app.extensions
    ):
        config = cast(_LabelConfig, app.config)
        state["prefix_before"] = config.autosectionlabel_prefix_document
        config.autosectionlabel_prefix_document = True


def _restore_labels(app: Sphinx, doctree: Any = None) -> None:
    state = app.env.domaindata.get(_KEY, {})
    if "prefix_before" in state:
        config = cast(_LabelConfig, app.config)
        config.autosectionlabel_prefix_document = state.pop("prefix_before")


def _record_outputs(app: Sphinx) -> None:
    if not isinstance(app.builder, StandaloneHTMLBuilder) or app.builder.name not in {
        "html",
        "dirhtml",
    }:
        return
    state = app.env.domaindata[_KEY]
    manifest = Path(app.outdir) / ".spdl-knowledge-base-pages.json"
    old = state["previous_pages"]
    if manifest.exists():
        names = json.loads(manifest.read_text(encoding="utf-8"))
        if not isinstance(names, list) or any(
            not isinstance(name, str) for name in names
        ):
            raise ConfigError("Invalid knowledge-base output manifest")
        old = set(names)
    for name in old:
        _destination(Path(app.srcdir), name + ".md")
    state["old_outputs"] = old
    _write_atomic(manifest, json.dumps(sorted(old | state["outputs"])))


def _validate_output(path: Path, outdir: Path) -> None:
    if not path.exists():
        return
    owner = "Generated by spdl_docs_knowledge_base; edit the original Markdown."
    if path.is_symlink() or not path.resolve().is_relative_to(outdir.resolve()):
        raise ConfigError(
            f"Knowledge-base output is outside its build directory: {path}"
        )
    if owner not in path.read_text(encoding="utf-8"):
        raise ConfigError(f"Refusing to remove unowned knowledge-base output: {path}")


def _publish_outputs(app: Sphinx) -> None:
    builder = app.builder
    if not isinstance(builder, StandaloneHTMLBuilder) or builder.name not in {
        "html",
        "dirhtml",
    }:
        return
    state = app.env.domaindata[_KEY]
    outdir = Path(app.outdir)
    current = state["outputs"]
    retired = []
    for name in sorted(state["old_outputs"] - current):
        retired.append(Path(builder.get_outfilename(name)))
        retired.append(
            outdir / "_sources" / f"{name}.md{app.config.html_sourcelink_suffix}"
        )
    for path in retired:
        _validate_output(path, outdir)
    for path in retired:
        path.unlink(missing_ok=True)
    _write_atomic(
        outdir / ".spdl-knowledge-base-pages.json", json.dumps(sorted(current))
    )


def _cleanup(app: Sphinx, exception: BaseException | None) -> None:
    lock = getattr(app, "_spdl_knowledge_base_lock", None)
    if lock is None or not lock.is_locked:
        return
    try:
        _remove_generated(Path(app.srcdir))
        if exception is None:
            _publish_outputs(app)
    except (ConfigError, OSError, ValueError) as error:
        if exception is None:
            raise
        exception.add_note(f"Knowledge-base cleanup also failed: {error}")
        logger.warning(
            "Knowledge-base cleanup failed after an earlier build error", exc_info=True
        )
    finally:
        _restore_labels(app)
        lock.release()
        delattr(app, "_spdl_knowledge_base_lock")


def setup(app: Sphinx) -> dict[str, Any]:
    """Register Markdown rendering, source generation and navigation hooks."""
    app.setup_extension(myst_parser.__name__)
    app.add_config_value("spdl_knowledge_base_sources", _default_sources(), "env")
    app.add_config_value("spdl_knowledge_base_extra_sources", [], "env")
    app.connect("builder-inited", _prepare)
    app.connect("env-before-read-docs", _read_docs)
    app.connect("source-read", _dependencies)
    app.connect("doctree-read", _navigation, priority=100)
    app.connect("doctree-read", _label_scope, priority=200)
    app.connect("doctree-read", _restore_labels, priority=800)
    app.connect("build-finished", _cleanup)
    return {"version": "1", "parallel_read_safe": True, "parallel_write_safe": True}
