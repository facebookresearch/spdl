"""Emit redirects for moved documentation pages on static HTML hosts."""

from __future__ import annotations

import os
import sys
from html import escape
from pathlib import Path
from urllib.parse import quote

# Paths relative to the HTML build root. Redirect straight to the current page.
_REDIRECTS = {
    "best_practice.html": "pipeline_guides/best_practice.html",
    "case_studies/index.html": "pipeline_guides/case_studies/index.html",
    "case_studies/data_format.html": "pipeline_guides/case_studies/data_format.html",
    "case_studies/inference.html": "pipeline_guides/case_studies/inference.html",
    "case_studies/ipc.html": "pipeline_guides/case_studies/ipc.html",
    "case_studies/parallelism.html": "pipeline_guides/case_studies/parallelism.html",
    "case_studies/shared_memory_arena.html": (
        "pipeline_guides/case_studies/shared_memory_arena.html"
    ),
}
_MARKER = "<!-- Generated by spdl_docs_redirects. -->"


def write_redirects(srcdir: Path, outdir: Path) -> None:
    """Write redirect stubs after a successful standalone HTML build."""
    for source, target in _REDIRECTS.items():
        if not (outdir / target).is_file():
            raise ValueError(f"Missing HTML redirect destination: {target}")
        # Sphinx can leave old HTML behind after a source file moves. Replace
        # that output, but never shadow a page that still has a source file.
        old_source = srcdir / source
        if any(old_source.with_suffix(suffix).exists() for suffix in (".rst", ".md")):
            raise ValueError(
                f"HTML redirect conflicts with a documentation source: {source}"
            )

    for source, target in _REDIRECTS.items():
        old = outdir / source
        relative = Path(os.path.relpath(outdir / target, old.parent)).as_posix()
        url = escape(quote(relative), quote=True)
        old.parent.mkdir(parents=True, exist_ok=True)
        old.write_text(
            f"""{_MARKER}
<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>Page moved</title>
<link id="destination" rel="canonical" href="{url}">
<meta name="robots" content="noindex">
<script>
const target = new URL(document.getElementById("destination").href);
target.search = window.location.search;
target.hash = window.location.hash;
window.location.replace(target.href);
</script>
<noscript><meta http-equiv="refresh" content="0; url={url}"></noscript>
</head>
<body><p>This page has moved to <a href="{url}">its new location</a>.</p></body>
</html>
""",
            encoding="utf-8",
        )


def _build_finished(app, exception: Exception | None) -> None:
    if exception is None and app.builder.name == "html":
        write_redirects(Path(app.srcdir), Path(app.outdir))


def setup(app) -> dict[str, bool]:
    app.connect("build-finished", _build_finished)
    return {"parallel_read_safe": True, "parallel_write_safe": True}


if __name__ == "__main__":
    write_redirects(Path(sys.argv[1]), Path(sys.argv[2]))
